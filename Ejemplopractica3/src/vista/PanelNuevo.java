    private void btbGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btbGuardarActionPerformed
              String error = ControlErrores.validarNumero(txtNumero.getText());
        if (error == null) error = ControlErrores.validarNombre(txtNombre.getText());
        if (error == null) error = ControlErrores.validarPuntos(txtPuntos.getText());
        if (error == null) error = ControlErrores.validarFecha(txtFecha.getText());

        if (error != null) {
            ControlErrores.mostrarError(lblError, error);   // JLabel rojo
            return;                                          // no seguimos
        }

        // 2. Todo correcto: convertir el texto a datos
        int numero = Integer.parseInt(txtNumero.getText().trim());
        String nombre = txtNombre.getText().trim();
        float puntos = Float.parseFloat(txtPuntos.getText().trim());
        LocalDate fecha = ControlErrores.convertirFecha(txtFecha.getText());

        // 3. Crear el cliente y añadirlo a la lista
        Cliente c = new Cliente(numero, nombre, puntos, fecha);
        if (!lista.anadirCliente(c)) {
            ControlErrores.mostrarError(lblError, "Ya existe un cliente con ese número.");
            return;
        }

        limpiar();
        JOptionPane.showMessageDialog(this, "Cliente añadido correctamente.");
    }//GEN-LAST:event_btbGuardarActionPerformed


