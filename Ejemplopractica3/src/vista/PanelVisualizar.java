        // Pinta el cliente actual en los campos y activa/desactiva botones
        public void mostrarCliente() {
            Cliente c = lista.obtenerClienteActual();

            if (c == null) {   // lista vacía
                txtNumero.setText("");
                txtNombre.setText("");
                txtPuntos.setText("");
                txtFecha.setText("");
                lblPosicion.setText("No hay clientes");
            } else {
                txtNumero.setText(String.valueOf(c.getNumero()));
                txtNombre.setText(c.getNombre());
                txtPuntos.setText(String.valueOf(c.getPuntos()));
                txtFecha.setText(c.getFechaNacimiento().format(DateTimeFormatter.ofPattern("dd/MM/yyyy")));
                lblPosicion.setText("Cliente " + (lista.getActual() + 1) + " de " + lista.size());
            }

            // Botones: solo activos cuando tienen sentido
            btnPrimero.setEnabled(!lista.esVacia() && !lista.esPrimero());
            btnAnterior.setEnabled(!lista.esVacia() && !lista.esPrimero());
            btnSiguiente.setEnabled(!lista.esVacia() && !lista.esUltimo());
            btnUltimo.setEnabled(!lista.esVacia() && !lista.esUltimo());
            btnBorrar.setEnabled(!lista.esVacia());
        }

